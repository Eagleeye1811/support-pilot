"""SYNTHETIC analytics dataset for the demo tenant (ShopNova, a fictional company).

Nothing here is real: ShopNova does not exist, so there is no real helpdesk export or real social media about it.
This module generates, reproducibly from a seed and an anchor date:
  * ``tickets``      — ~180 days of helpdesk history (the "previous helpdesk export"), with CSAT
  * ``social_posts`` — public-feedback-style posts (X/Instagram-like), clearly marked synthetic
  * ``events``       — the business event log (releases, gateway incidents, courier disruption, defects, outages …)
  * ``gateway_daily``— operational payment stats per gateway and day
  * ``truth``        — the generator's ground truth (which events really drive which complaints). It is returned
                       for tests only and is NEVER written to the warehouse or used by the analytics.

Every record carries ``source`` = "synthetic"; the dashboard labels it as such. The data deliberately contains
quality defects — exact duplicates, re-exported rows, missing fields, inconsistent channel/intent spellings,
mixed timestamp formats, out-of-range ratings, impossible timestamps — so the cleaning step is exercised.

Causal structure (known by construction, so analytics can be checked against it):
  * PayFast degradation (two windows) → payment_failure ×4, double_charge ×2, mostly on PayFast; gateway failure rate ↑
  * SwiftShip monsoon disruption → delivery_delay ×2.5 on SwiftShip
  * App release v5.2 → login_issue ×3, password_reset ×1.6, mostly in-app
  * Air Fryer (HM-044) batch defect → damaged_item ×3 on HM-044
  * NovaFiber Andheri West outage → network_issue ×4 in Andheri West
  * Diwali sale → volume ×1.5 on order-related intents (demand, not a defect)
  * Homepage redesign → NO effect (control event: any "finding" about it is a false positive)
  * Emerging (last 4 days): wallet top-up failures after app v5.6 — loud on social, barely in tickets yet
  * Refunds resolved by the AI without a human are rated much worse than human-handled refunds
Escalation and CSAT are noisy functions of intent, tier, emotion, repeat contact, channel, incident load and
resolution speed, so predictive models have real (but synthetic) signal to learn and baselines to beat.
"""
