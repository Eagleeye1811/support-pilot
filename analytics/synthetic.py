def _poisson(rng, lam):
    if lam <= 0:
        return 0
    if lam > 30:
        return max(0, int(round(rng.gauss(lam, math.sqrt(lam)))))
    k, p, limit = 0, 1.0, math.exp(-lam)
    while True:
        p *= rng.random()
        if p <= limit:
            return k
        k += 1


def _sigmoid(x):
    return 1 / (1 + math.exp(-x))


def make(anchor=None, seed=7, days=DAYS, defects=True):
    """Generate the synthetic dataset. Same (anchor, seed) → identical output."""
    rng = random.Random(seed)
    anchor = (anchor or dt.datetime.now(dt.timezone.utc)).astimezone(dt.timezone.utc).replace(minute=0, second=0, microsecond=0)
    day0 = anchor.replace(hour=0)

    def day_start(d):  # d days before the anchor day
        return day0 - dt.timedelta(days=d)

    events = []
    for i, (name, kind, start, end, attrs, _) in enumerate(EVENTS, 1):
        events.append(dict(id=f"EV-{i:03d}", name=name, kind=kind, start=day_start(start).isoformat(),
                           end=(day_start(end) if end else anchor).isoformat(), attributes=attrs, source="synthetic",
                           note="synthetic business event log"))
    truth = {e[0]: dict(effects=e[5], attributes=e[4]) for e in EVENTS}

    def active(d):  # an event covers days (end, start]; end == 0 means still ongoing today
        return [e for e in EVENTS if e[3] < d <= e[2] or (e[3] == 0 and d == 0)]

    customers = [dict(id=f"SYN-C{i:05d}", tier=rng.choices(["Standard", "Plus", "Premium"], [0.62, 0.25, 0.13])[0])
                 for i in range(1, 1501)]
    heavy = customers[:120]  # a minority contacts support often
    tickets, social, gateway_daily = [], [], []
    history = {}  # customer → list of created datetimes (for repeat-contact behaviour)
    seq = 0
    for d in range(days, -1, -1):
        start = day_start(d)
        if start > anchor:
            continue
        acts = active(d)
        dow = start.weekday()
        trend = 1 + 0.0015 * (days - d)
        lam = 44 * DOW[dow] * trend
        weights = dict(BASE_WEIGHTS)
        for name, _, _, _, _, eff in acts:
            for intent, mult in eff.items():
                weights[intent] = weights[intent] * mult
        lam *= sum(weights.values()) / sum(BASE_WEIGHTS.values())
        hours = 24 if d else max(1, anchor.hour)
        n = _poisson(rng, lam * hours / 24)
        incident_load = sum(1 for e in acts if e[1] in ("incident", "outage", "product", "release") and e[5])
        # gateway operational stats
        for g in GATEWAYS:
            attempts = int(2600 * DOW[dow] * trend * (1.0 if g == "PayFast" else 0.7))
            rate = 0.018 + rng.gauss(0, 0.003)
            if g == "PayFast" and any(e[4].get("gateway") == "PayFast" for e in acts):
                rate = 0.09 + rng.gauss(0, 0.01)
            gateway_daily.append(dict(date=start.date().isoformat(), gateway=g, attempts=attempts,
                                      failures=max(0, int(attempts * max(rate, 0.002))), source="synthetic"))
        for _ in range(n):
            seq += 1
            intent = rng.choices(list(weights), list(weights.values()))[0]
            created = start + dt.timedelta(seconds=rng.uniform(0, hours * 3600 - 1))
            cust = rng.choice(heavy) if rng.random() < 0.3 else rng.choice(customers)
            prior = [t for t in history.get(cust["id"], []) if (created - t).days < 30]
            spec = INTENTS[intent]
            meta, product = {}, rng.choice(list(SKUS))
            if intent in ("payment_failure", "double_charge"):
                pf = any(e[4].get("gateway") == "PayFast" for e in acts)
                meta["gateway"] = "PayFast" if (pf and rng.random() < 0.85) else rng.choice(GATEWAYS)
            elif intent in ("delivery_delay", "wrong_item"):
                ss = any(e[4].get("courier") == "SwiftShip" for e in acts)
                meta["courier"] = "SwiftShip" if (ss and rng.random() < 0.8) else rng.choice(COURIERS)
            elif intent in ("damaged_item", "return_request", "refund_request"):
                af = any(e[4].get("sku") == "HM-044" for e in acts) and intent == "damaged_item"
                product = "HM-044" if (af and rng.random() < 0.75) else product
                meta["sku"] = product
            elif intent in ("network_issue", "technician_visit"):
                ao = any(e[4].get("area") == "Andheri West" for e in acts)
                meta["area"] = "Andheri West" if (ao and rng.random() < 0.8) else rng.choice(AREAS)
            # emotion: more anger for repeat contacts and during incidents
            anger = -1.6 + 0.55 * len(prior) + 0.5 * (incident_load > 0) + (0.6 if spec["category"] == "Billing" else 0)
            u = rng.random()
            emotion = "angry" if u < _sigmoid(anger - 1.2) else ("frustrated" if u < _sigmoid(anger + 0.4) else "calm")
            text = rng.choice(TEMPLATES[intent]).format(d=rng.randint(2, 9), courier=meta.get("courier", "the courier"),
                                                        product=SKUS[product], area=meta.get("area", "my area"))
            text += rng.choice(ANGRY) if emotion == "angry" else (rng.choice(FRUSTRATED) if emotion == "frustrated" else "")
            channel = rng.choices(["web", "whatsapp", "email", "app", "telegram"], [0.36, 0.27, 0.15, 0.16, 0.06])[0]
            if intent in ("login_issue", "password_reset") and any(e[0] == "App release v5.2" for e in acts):
                channel = "app" if rng.random() < 0.6 else channel
            # escalation: noisy function of observable-at-creation features (+ unobserved noise)
            base = {"fraud_report": 6, "legal_request": 6, "human_agent": 5, "subscription_not_active": 0.6,
                    "damaged_item": 0.0, "technician_visit": 0.1, "refund_request": -0.8, "double_charge": -0.9}.get(intent, -2.3)
            z = (base + (0.7 if emotion == "angry" else 0.25 if emotion == "frustrated" else 0) + 0.45 * min(len(prior), 4)
                 + (0.35 if cust["tier"] == "Premium" else 0) + (0.4 if channel == "email" else 0)
                 + 0.35 * incident_load + rng.gauss(0, 0.7))
            escalated = rng.random() < _sigmoid(z)
            tier, prio = cust["tier"], spec["priority"]
            if emotion == "angry" and prio in ("low", "medium"):
                prio = "high" if prio == "medium" else "medium"
            team = spec["team"] if escalated else "AI Agent"
            t = dict(id=f"HD-{seq:06d}", created_at=created.isoformat(), customer_id=cust["id"], tier=tier, channel=channel,
                     intent=intent, category=spec["category"], priority=prio, first_message=text, escalated=escalated,
                     team=team, meta=meta, source="synthetic")
            # response / resolution
            load = 1 + 0.5 * incident_load + (0.3 if dow >= 5 else 0)
            if not escalated:
                fr = created + dt.timedelta(seconds=rng.uniform(5, 60))
                res = created + dt.timedelta(minutes=rng.uniform(1, 12))
            else:
                fr = created + dt.timedelta(minutes=SLA_RESPONSE[tier][prio] * rng.lognormvariate(-0.3, 0.6) * load)
                res = created + dt.timedelta(minutes=SLA_RESOLUTION[tier][prio] * rng.lognormvariate(-0.35, 0.55) * load)
            resolved = res <= anchor - dt.timedelta(minutes=5)
            breach = resolved and (res - created).total_seconds() / 60 > SLA_RESOLUTION[tier][prio]
            reopened = resolved and rng.random() < (0.05 + 0.08 * breach + 0.05 * (emotion == "angry"))
            t.update(first_response_at=fr.isoformat() if fr <= anchor else None, resolved_at=res.isoformat() if resolved else None,
                     status=("Closed" if resolved and (anchor - res).days >= 1 else "Resolved") if resolved else
                     rng.choice(["Assigned", "Pending Customer", "Opened"]), reopened=reopened,
                     resolved_by=("SupportPilot AI" if not escalated else "Human") if resolved else None)
            if resolved and rng.random() < 0.55:
                hours_to_res = (res - created).total_seconds() / 3600
                score = (4.85 - 0.9 * breach - 0.35 * escalated - 0.55 * (emotion == "angry") - 0.25 * (emotion == "frustrated")
                         - 0.7 * reopened - 0.12 * min(hours_to_res / 24, 5) - 0.2 * min(len(prior), 3)
                         - (2.2 if intent == "refund_request" and not escalated else 0) + rng.gauss(0, 0.75))
                t["csat"] = max(1, min(5, int(round(score))))
            tickets.append(t)
            history.setdefault(cust["id"], []).append(created)
        # social posts for the day
        mult = {}
        for e in acts:
            if e[0] in SOCIAL_EVENT_TOPIC:
                topic, m = SOCIAL_EVENT_TOPIC[e[0]]
                mult[topic] = max(mult.get(topic, 1), m)
        for topic, base in SOCIAL_BASE.items():
            k = _poisson(rng, base * mult.get(topic, 1) * DOW[dow] * hours / 24)
            for _ in range(k):
                tmpl = rng.choice(SOCIAL_TOPICS[topic])
                if mult.get(topic, 1) > 1 and any(w in tmpl for w in POSITIVE_TEMPLATES) and rng.random() < 0.8:
                    tmpl = SOCIAL_TOPICS[topic][0]  # incidents make posts complaints
                text = tmpl.format(d=rng.randint(2, 12), courier=rng.choice(COURIERS), product=SKUS[rng.choice(list(SKUS))],
                                   area=rng.choice(AREAS) if topic != "broadband" or "Andheri West" not in
                                   [e[4].get("area") for e in acts] else "Andheri West")
                ts = start + dt.timedelta(seconds=rng.uniform(0, hours * 3600 - 1))
                pid = hashlib.sha1(f"{seed}-{ts.isoformat()}-{text}-{rng.random()}".encode()).hexdigest()[:12]
                social.append(dict(id=f"SYN-P-{pid}", platform="synthetic-social", created_at=ts.isoformat(), text=text,
                                   author=f"syn_user_{rng.randint(1, 4000):04d}", likes=int(rng.expovariate(1 / 6)),
                                   reposts=int(rng.expovariate(1 / 2)), lang="en", url=None, source="synthetic",
                                   topic_truth=topic))
        # irrelevant posts (off-brand) that the pipeline must filter out
        for _ in range(_poisson(rng, 3)):
            ts = start + dt.timedelta(seconds=rng.uniform(0, hours * 3600 - 1))
            social.append(dict(id=f"SYN-P-x{seq}{rng.randint(0, 10**6)}", platform="synthetic-social", created_at=ts.isoformat(),
                               text=rng.choice(["Cricket match tonight!!", "new phone who dis", "Monsoon traffic is crazy"]),
                               author=f"syn_user_{rng.randint(1, 4000):04d}", likes=0, reposts=0, lang="en", url=None,
                               source="synthetic", topic_truth=None))
    for p in social:
        p.pop("topic_truth", None)
    if defects:
        tickets, social = _inject_defects(rng, tickets, social)
    return dict(label=LABEL, seed=seed, anchor=anchor.isoformat(), days=days, tickets=tickets, social_posts=social,
                events=events, gateway_daily=gateway_daily, truth=truth)


def _inject_defects(rng, tickets, social):
    """Realistic export problems the cleaning step must handle."""
    out = []
    variants = {"whatsapp": ["WhatsApp", "whatsapp ", "WA"], "web": ["Web Chat", "website"], "email": ["E-mail", "EMAIL"],
                "app": ["Mobile App", "APP"]}
    for t in tickets:
        t = dict(t)
        r = rng.random()
        if r < 0.02:
            t["channel"] = None
        elif r < 0.06 and t["channel"] in variants:
            t["channel"] = rng.choice(variants[t["channel"]])
        if rng.random() < 0.015:
            t["tier"] = None
        if rng.random() < 0.02:
            t["intent"] = t["intent"].replace("_", " ").title()        # "Payment Failure"
        if rng.random() < 0.02:  # local-time string export
            local = dt.datetime.fromisoformat(t["created_at"]).astimezone(dt.timezone(dt.timedelta(hours=5, minutes=30)))
            t["created_at"] = local.strftime("%d/%m/%Y %H:%M")
        if t.get("csat") is not None and rng.random() < 0.04:
            t["csat"] = rng.choice([str(t["csat"]), f"{t['csat']}/5", 0, 7])
        if t.get("resolved_at") and rng.random() < 0.004:
            t["resolved_at"] = (dt.datetime.fromisoformat(t["created_at"].replace("Z", "")) - dt.timedelta(hours=3)).isoformat() \
                if "/" not in t["created_at"] else t["resolved_at"]
        out.append(t)
        if rng.random() < 0.02:
            out.append(dict(t))                                        # exact duplicate row
        elif rng.random() < 0.01 and t.get("resolved_at"):
            stale = dict(t, status="Assigned", resolved_at=None, csat=None, export_version=0)
            out.insert(len(out) - 1, stale)                            # older export of the same ticket
    social_out = []
    for p in social:
        social_out.append(p)
        if rng.random() < 0.03:
            social_out.append(dict(p))                                 # duplicate from paging overlap
    return out, social_out
